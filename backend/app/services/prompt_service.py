def build_system_prompt() -> str:
    return (
        "Ты ИИ-юрист ассистент. Помогай пользователю разбирать договоры, претензии, "
        "исковые заявления, переписку и правовые риски. Отвечай структурированно и "
        "понятным языком.\n\n"
        "Правила ответа:\n"
        "1. Не выдавай себя за человека-юриста и не утверждай, что это официальная юридическая консультация.\n"
        "2. Всегда предупреждай, что ответ носит информационный характер и для критичных решений нужен юрист.\n"
        "3. Если данных не хватает, сначала скажи об этом явно.\n"
        "4. Не выдумывай факты, статьи закона, судебную практику или документы.\n"
        "5. Пиши на русском языке."
    )


def build_rag_prompt(question: str, rag_context: str) -> str:
    return (
        "Используй только предоставленный контекст.\n"
        "Если информации нет или её недостаточно, так и скажи.\n"
        "Не выдумывай статьи, факты и источники.\n"
        "Если в контексте встречается официальный акт с pravo.gov.ru или publication.pravo.gov.ru, "
        "попробуй указать конкретную статью/пункт в поле article_label.\n"
        "В поле article_url верни ссылку на конкретную статью, если она явно есть в контексте. "
        "Если отдельной ссылки на статью нет, верни ссылку на официальный документ pravo.gov.ru.\n"
        "Цитируй только то, что реально есть в контексте.\n\n"
        "Верни ответ строго в JSON без markdown и без дополнительных пояснений.\n"
        "Формат JSON:\n"
        "{\n"
        '  "answer": "краткий юридический ответ по контексту",\n'
        '  "citations": [\n'
        '    {\n'
        '      "title": "например: Источник 1 или название акта",\n'
        '      "quote": "короткая цитата из контекста",\n'
        '      "article_label": "например: статья 15 ГК РФ",\n'
        '      "article_url": "https://publication.pravo.gov.ru/...",\n'
        '      "document_id": 1,\n'
        '      "knowledge_base_id": null,\n'
        '      "filename": "contract.docx",\n'
        '      "source_url": null\n'
        "    }\n"
        "  ],\n"
        '  "confidence_score": 0.0,\n'
        '  "refusal_reason": null,\n'
        '  "source_validation": "подтверждено контекстом / частично подтверждено / недостаточно данных"\n'
        "}\n\n"
        f"{rag_context}\n\n"
        f"Вопрос пользователя:\n{question}"
    )


def build_analysis_prompt(
    *,
    analysis_type: str,
    document_text: str,
    question: str | None,
    filename: str | None = None,
) -> str:
    header = f"Тип анализа: {analysis_type}\n"
    if filename:
        header += f"Имя файла: {filename}\n"

    prompt = (
        f"{header}"
        "Нужно:\n"
        "1. Кратко резюмировать документ.\n"
        "2. Выделить юридические риски.\n"
        "3. Отметить спорные или опасные формулировки.\n"
        "4. Дать рекомендации по следующим шагам.\n"
    )
    if question:
        prompt += f"5. Отдельно ответить на вопрос пользователя: {question}\n"

    prompt += f"\nТекст документа:\n{document_text}"
    return prompt
